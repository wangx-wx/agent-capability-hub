import { test, expect } from "@playwright/test";

test("role grants, user keys, formal calls and private usage statistics form a complete browser loop", async ({ page }, testInfo) => {
  await page.goto("/");
  await page.getByLabel("账号").fill("browser-admin");
  await page.getByLabel("密码", { exact: true }).fill("browser-test-password");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await expect(page.getByRole("button", { name: "角色与授权", exact: true })).toBeVisible();
  const targets = await (await page.request.get("http://127.0.0.1:3310/__fixture__/targets")).json();
  const service = await (await page.request.post("/api/admin/services", { data: { name: "User Tools", namespace: "usage", kind: "mcp", url: targets.mcp, enabled: true } })).json();
  const preview = await (await page.request.post(`/api/admin/services/${service.service.id}/sync-preview`)).json();
  await page.request.post(`/api/admin/services/${service.service.id}/sync-confirm`, { data: { previewId: preview.preview.id } });
  await page.getByRole("button", { name: "角色与授权", exact: true }).click();
  await page.getByLabel("新角色名称", { exact: true }).fill("Browser Caller");
  await page.getByRole("button", { name: "创建角色", exact: true }).click();
  await page.getByRole("checkbox", { name: /usage__echo/ }).check();
  await page.getByRole("button", { name: "保存授权", exact: true }).click();
  await page.getByRole("button", { name: "用户", exact: true }).click();
  await page.getByLabel("账号", { exact: true }).fill("browser-user");
  await page.getByRole("checkbox", { name: "Browser Caller", exact: true }).check();
  await page.getByRole("button", { name: "创建用户", exact: true }).click();
  const password = (await page.getByRole("dialog").locator("code").textContent())!.trim();
  await page.getByRole("button", { name: "完成", exact: true }).click();
  await page.getByRole("button", { name: "退出", exact: true }).click();
  await expect(page.getByRole("heading", { name: "登录控制台" })).toBeVisible();
  await page.getByLabel("账号").fill("browser-user");
  await page.getByLabel("密码", { exact: true }).fill(password);
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByRole("button", { name: "API Keys", exact: true }).click();
  await page.getByLabel("名称", { exact: true }).fill("Browser Agent");
  await page.getByRole("combobox", { name: "有效期", exact: true }).selectOption("permanent");
  await page.getByRole("button", { name: "创建 Key", exact: true }).click();
  const key = (await page.getByRole("dialog").locator("code").textContent())!.trim();
  await page.getByRole("button", { name: "完成", exact: true }).click();
  const headers = { Authorization: `Bearer ${key}`, Accept: "application/json, text/event-stream" };
  const success = await page.request.post("/mcp", { headers, data: { jsonrpc: "2.0", id: 1, method: "tools/call", params: { name: "usage__echo", arguments: { text: "user hello" } } } });
  expect(await success.text()).toContain("user hello");
  await page.request.post("/mcp", { headers, data: { jsonrpc: "2.0", id: 2, method: "tools/call", params: { name: "usage__count", arguments: {} } } });
  await page.getByRole("button", { name: "概览", exact: true }).click();
  await expect(page.getByTestId("usage-total")).toHaveText("2");
  await expect(page.getByTestId("usage-successful")).toHaveText("1");
  await expect(page.getByTestId("usage-failed")).toHaveText("1");
  await expect(page.getByRole("button", { name: "调用审计", exact: true })).toHaveCount(0);
  expect((await page.request.get("/api/admin/audit")).status()).toBe(403);
  await page.screenshot({ path: testInfo.outputPath("user-usage.png"), fullPage: true });
  await page.getByRole("button", { name: "退出", exact: true }).click();
  await expect(page.getByRole("heading", { name: "登录控制台" })).toBeVisible();
  await page.getByLabel("账号").fill("browser-admin");
  await page.getByLabel("密码", { exact: true }).fill("browser-test-password");
  await page.getByRole("button", { name: "登录", exact: true }).click();
  await page.getByRole("button", { name: "调用审计", exact: true }).click();
  await expect(page.getByRole("cell", { name: "usage__echo", exact: true })).toBeVisible();
});
